"""Generates g_tables.rs: [d]G and [d](2^128 G) for d in [-128, 128], d != 0.

    gen_tables.py           rewrite g_tables.rs next to this script
    gen_tables.py --check   exit 1 if g_tables.rs is not what this script generates
"""

import sys
from pathlib import Path

P = 2**256 - 2**32 - 977
G = (0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798,
     0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8)
HALF = 128
OUT = Path(__file__).resolve().parent / "g_tables.rs"


def add(a, b):
    if a is None:
        return b
    if a[0] == b[0]:
        if (a[1] + b[1]) % P == 0:
            return None
        m = 3 * a[0] * a[0] * pow(2 * a[1], -1, P)
    else:
        m = (b[1] - a[1]) * pow(b[0] - a[0], -1, P)
    x = (m * m - a[0] - b[0]) % P
    return x, (m * (a[0] - x) - a[1]) % P


def limbs(v):
    return ", ".join(f"0x{(v >> (64 * i)) & (2**64 - 1):016X}" for i in range(4))


def table(name, base, doc):
    multiples, point = [], None
    for _ in range(HALF):
        point = add(point, base)
        multiples.append(point)
    entries = [(x, P - y) for x, y in reversed(multiples)] + [(0, 0)] + multiples
    lines = [f"/// {doc}", f"pub(crate) static {name}: [SyscallPoint256; {2 * HALF + 1}] = ["]
    for x, y in entries:
        lines.append(f"    SyscallPoint256 {{ x: [{limbs(x)}], y: [{limbs(y)}] }},")
    lines.append("];")
    return "\n".join(lines)


def generate():
    shifted = G
    for _ in range(128):
        shifted = add(shifted, shifted)
    header = ("// Generated by gen_tables.py. Do not edit.\n\n"
              "use crate::syscalls::SyscallPoint256;\n\n"
              f"/// Index of the unused zero entry; entry `G_TABLE_MID + d` holds d times the base.\n"
              f"pub(crate) const G_TABLE_MID: usize = {HALF};\n")
    return "\n".join([
        header,
        table("G_TABLE", G, "[d]G for d in [-128, 128]; the middle entry is unused."),
        "",
        table("G_SHIFTED_TABLE", shifted, "[d](2^128·G) for d in [-128, 128]; the middle entry is unused."),
        "",
    ])


def main():
    text = generate()
    if sys.argv[1:] == ["--check"]:
        if OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT.name} is stale; run {Path(__file__).name}")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
