"""Generates g_tables.rs: [d]G and [d](2^128 G) for d in [0, 2^G_WINDOW), the offset point T and -[2^128]T.

    gen_tables.py           rewrite g_tables.rs next to this script
    gen_tables.py --check   exit 1 if g_tables.rs is not what this script generates
"""

import hashlib
import sys
from pathlib import Path

P = 2**256 - 2**32 - 977
G = (0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798,
     0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8)
G_WINDOW = 12
OFFSET_SEED = b"nethermind/secp256k1/straus/offset"
OUT = Path(__file__).resolve().parent / "g_tables.rs"


def add(a, b):
    if a is None:
        return b
    if a[0] == b[0]:
        if (a[1] + b[1]) % P == 0:
            return None
        m = 3 * a[0] * a[0] * pow(2 * a[1], -1, P)
    else:
        m = (b[1] - a[1]) * pow(b[0] - a[0], -1, P)
    x = (m * m - a[0] - b[0]) % P
    return x, (m * (a[0] - x) - a[1]) % P


def shift(point, bits):
    for _ in range(bits):
        point = add(point, point)
    return point


def offset_point():
    """The first curve point whose x is SHA-256(seed || counter): a base nobody knows a logarithm of."""
    counter = 0
    while True:
        x = int.from_bytes(hashlib.sha256(OFFSET_SEED + counter.to_bytes(4, "big")).digest(), "big")
        a = (x * x * x + 7) % P
        y = pow(a, (P + 1) // 4, P)
        if x < P and y * y % P == a:
            return x, y if y % 2 == 0 else P - y
        counter += 1


def limbs(v):
    return ", ".join(f"0x{(v >> (64 * i)) & (2**64 - 1):016X}" for i in range(4))


def point(p):
    return f"SyscallPoint256 {{ x: [{limbs(p[0])}], y: [{limbs(p[1])}] }}"


def table(name, base, doc):
    size = 1 << G_WINDOW
    lines = [f"/// {doc}", f"pub(crate) static {name}: [SyscallPoint256; {size}] = [", f"    {point((0, 0))},"]
    multiple = None
    for _ in range(1, size):
        multiple = add(multiple, base)
        lines.append(f"    {point(multiple)},")
    lines.append("];")
    return "\n".join(lines)


def generate():
    offset = offset_point()
    shifted = shift(offset, 128)
    header = ("// Generated by gen_tables.py. Do not edit.\n\n"
              "use crate::syscalls::SyscallPoint256;\n\n"
              f"/// Width of the unsigned digits that index the tables below.\n"
              f"pub(crate) const G_WINDOW: u32 = {G_WINDOW};\n")
    return "\n".join([
        header,
        "/// A point nobody knows a logarithm of, which starts the accumulator instead of infinity.",
        f"pub(crate) const OFFSET: SyscallPoint256 = {point(offset)};",
        "",
        "/// -[2^128]OFFSET, which removes the offset after the 128 doublings.",
        f"pub(crate) const OFFSET_SHIFTED_NEG: SyscallPoint256 = {point((shifted[0], P - shifted[1]))};",
        "",
        table("G_TABLE", G, f"[d]G for d in [0, 2^{G_WINDOW}); the zero entry is unused."),
        "",
        table("G_SHIFTED_TABLE", shift(G, 128), f"[d](2^128·G) for d in [0, 2^{G_WINDOW}); the zero entry is unused."),
        "",
    ])


def main():
    text = generate()
    if sys.argv[1:] == ["--check"]:
        if OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT.name} is stale; run {Path(__file__).name}")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
